/** Build printable Fee Challan HTML */
export function buildChallanPrint(challan, institutionName) {
  const isPaid = (challan.status || '').toLowerCase() === 'paid';
  return `
    <table class="info">
      <tr><td class="label">Student Name</td><td>${challan.studentName || '—'}</td></tr>
      <tr><td class="label">Class / Batch</td><td>${challan.className || challan.batchName || '—'}</td></tr>
      <tr><td class="label">Month</td><td>${challan.monthLabel || challan.month || '—'}</td></tr>
      <tr><td class="label">Challan No.</td><td>${challan.id || '—'}</td></tr>
      <tr><td class="label">Status</td><td>
        <span class="${isPaid ? 'status-paid' : 'status-unpaid'}">${isPaid ? 'PAID' : 'UNPAID'}</span>
      </td></tr>
    </table>

    <div class="amount-box">
      <div class="label">Amount Payable</div>
      <div class="value">Rs ${Number(challan.amount || 0).toLocaleString('en-PK')}</div>
    </div>

    ${isPaid && challan.paidOn ? `
      <p style="text-align:center;font-size:12px;color:#065f46;margin-top:8px">
        Paid on: ${new Date(challan.paidOn).toLocaleDateString('en-PK')}
      </p>
    ` : ''}

    <div class="signatures">
      <div class="sig"><div class="line">Received By</div></div>
      <div class="sig"><div class="line">Cashier / Accountant</div></div>
    </div>
  `;
}

/** Build printable Certificate HTML */
export function buildCertificatePrint(data, institutionName) {
  return `
    <div class="cert-body">
      <h2>Certificate of ${data.type || 'Completion'}</h2>
      <p style="margin:12px 0;font-size:14px">This is to certify that</p>
      <div class="student-name">${data.studentName || '—'}</div>
      <p style="margin:12px 0;font-size:14px;max-width:480px;margin-left:auto;margin-right:auto;line-height:1.6">
        ${data.body || `has successfully completed the requirements of <strong>${data.course || data.className || 'the program'}</strong> at ${institutionName}.`}
      </p>
      <p style="margin-top:20px;font-size:13px;color:#555">
        Date: ${data.date || new Date().toLocaleDateString('en-PK', { day: '2-digit', month: 'long', year: 'numeric' })}
      </p>
    </div>

    <div class="signatures">
      <div class="sig"><div class="line">Principal / Director</div></div>
      <div class="sig"><div class="line">Authorized Signature</div></div>
    </div>
  `;
}
